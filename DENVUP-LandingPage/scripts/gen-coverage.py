#!/usr/bin/env python3
"""Generate the technique JSON and the human-readable coverage matrix.

Usage:  python3 scripts/gen-coverage.py

Outputs
-------
src/data/techniques.json   — consumed by the website (src/data/techniques.ts)
ANIMATION_COVERAGE_MATRIX.md — the required deliverable, one row per technique

Both files are derived from scripts/techniques.py, so the matrix can never
drift away from the code that implements it.
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import techniques as tech  # noqa: E402

STATUS_ORDER = ["Tested", "Planned", "Requires revision", "Blocked"]


def slug(text: str) -> str:
    out = []
    for ch in text.lower():
        if ch.isalnum():
            out.append(ch)
        elif out and out[-1] != "-":
            out.append("-")
    return "".join(out).strip("-")


def main() -> int:
    records = tech.build()

    json_path = ROOT / "src" / "data" / "techniques.json"
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(
        json.dumps(
            {
                "total": len(records),
                "categories": [
                    {"index": index, "label": label, "count": len(names)}
                    for index, (label, names) in enumerate(tech.CATEGORIES, start=1)
                ],
                "techniques": records,
            },
            indent=2,
            ensure_ascii=False,
        )
        + "\n",
        encoding="utf-8",
    )

    counts: dict[str, int] = {}
    for record in records:
        counts[record["status"]] = counts.get(record["status"], 0) + 1

    by_category: dict[int, list[dict]] = {}
    for record in records:
        by_category.setdefault(record["cat"], []).append(record)

    lines: list[str] = []
    lines.append("# Animation coverage matrix")
    lines.append("")
    lines.append(
        "Every one of the 480 numbered techniques in "
        "`AI_Skills_Pack/Website_Animation_Interaction_Encyclopedia.md` is listed below with the "
        "status of its implementation on the DENVUP site, the file that implements it, and an "
        "honest note about what was verified."
    )
    lines.append("")
    lines.append(
        "This file is generated by `scripts/gen-coverage.py` from `scripts/techniques.py`, which is "
        "the single source of truth for both the catalogue and the coverage map. Regenerate it with:"
    )
    lines.append("")
    lines.append("```bash")
    lines.append("python3 scripts/gen-coverage.py")
    lines.append("```")
    lines.append("")
    lines.append("## Totals")
    lines.append("")
    lines.append("| Status | Count |")
    lines.append("| --- | ---: |")
    for status in STATUS_ORDER:
        lines.append(f"| {status} | {counts.get(status, 0)} |")
    lines.append(f"| **Total** | **{len(records)}** |")
    lines.append("")
    lines.append("### Status definitions")
    lines.append("")
    lines.append(
        "- **Tested** — implemented in the site and exercised by the verification pass described in "
        "`TESTING_REPORT.md`."
    )
    lines.append(
        "- **Planned** — not implemented yet. Every technique in this repository is either Tested, "
        "Blocked or Requires revision, so this count is zero."
    )
    lines.append(
        "- **Requires revision** — implemented, but the implementation is an approximation of the "
        "encyclopedia entry, or it could not be fully verified in this environment."
    )
    lines.append(
        "- **Blocked** — deliberately not implemented, with the technical reason stated in the note."
    )
    lines.append("")
    lines.append("## Coverage by category")
    lines.append("")
    lines.append("| # | Category | Techniques | Tested | Blocked | Requires revision |")
    lines.append("| ---: | --- | ---: | ---: | ---: | ---: |")
    for cat_index, (label, names) in enumerate(tech.CATEGORIES, start=1):
        rows = by_category.get(cat_index, [])
        tested = sum(1 for r in rows if r["status"] == "Tested")
        blocked = sum(1 for r in rows if r["status"] == "Blocked")
        revision = sum(1 for r in rows if r["status"] == "Requires revision")
        lines.append(
            f"| {cat_index} | {label} | {len(names)} | {tested} | {blocked} | {revision} |"
        )
    lines.append("")
    lines.append("## Full matrix")
    lines.append("")
    for cat_index, (label, names) in enumerate(tech.CATEGORIES, start=1):
        rows = by_category.get(cat_index, [])
        lines.append(f"### {cat_index}. {label}")
        lines.append("")
        lines.append("| ID | Technique | Status | Implemented in | Notes |")
        lines.append("| ---: | --- | --- | --- | --- |")
        for record in rows:
            note = record["note"].replace("|", "\\|")
            comp = record["comp"]
            comp_cell = f"`{comp}`" if comp not in ("n/a", "") else "—"
            lines.append(
                f"| {record['id']} | {record['name']} | {record['status']} | {comp_cell} | {note} |"
            )
        lines.append("")

    matrix_path = ROOT / "ANIMATION_COVERAGE_MATRIX.md"
    matrix_path.write_text("\n".join(lines), encoding="utf-8")

    print(f"wrote {json_path.relative_to(ROOT)} ({len(records)} techniques)")
    print(f"wrote {matrix_path.relative_to(ROOT)}")
    for status in STATUS_ORDER:
        print(f"  {status}: {counts.get(status, 0)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
