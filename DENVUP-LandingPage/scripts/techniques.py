def build() -> list[dict]:
    """Flatten the catalogue into a list of technique records."""
    records: list[dict] = []
    number = 0
    for cat_index, (label, names) in enumerate(CATEGORIES, start=1):
        for name in names:
            number += 1
            status, comp, note = COVERAGE.get(number, ("Planned", "n/a", "Not yet implemented."))
            records.append(
                {
                    "id": number,
                    "name": name,
                    "cat": cat_index,
                    "catLabel": label,
                    "status": status,
                    "comp": comp,
                    "note": note,
                }
            )
    expected = 480
    if number != expected:
        raise SystemExit(f"catalogue has {number} techniques, expected {expected}")
    missing = [r["id"] for r in records if r["status"] == "Planned"]
    return records


if __name__ == "__main__":
    recs = build()
    counts: dict[str, int] = {}
    for r in recs:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    print("total:", len(recs))
    for key, value in sorted(counts.items()):
        print(f"  {key}: {value}")
